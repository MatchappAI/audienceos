import { useState } from "react";
import { Link } from "react-router-dom";
import { patch } from "../api";
import { money } from "../format";
import { Demo, Empty, ErrorBox, Loading, Status, useApi, useAsync } from "../components/ui";

export const INDEX_NOTE = "Relative attractiveness for testing (0–100) — not a probability of success.";

export function ScoreChip({ v }: { v: any }) {
  return <span className="score" title={INDEX_NOTE}>{v == null ? "—" : Math.round(v)}</span>;
}

export function OpportunityList({ audienceId }: { audienceId?: string }) {
  const [status, setStatus] = useState("");
  const qs = new URLSearchParams();
  if (audienceId) qs.set("audience_id", audienceId);
  if (status) qs.set("status", status);
  const { data, error, loading, reload } = useApi<any[]>(`/api/opportunities?${qs}`);
  const act = useAsync();
  const setSt = async (id: string, s: string) => { if (await act.run(() => patch(`/api/opportunities/${id}`, { status: s }))) reload(); };

  return (
    <div className="stack">
      <div className="row between">
        <div className="seg">
          {[["", "All"], ["proposed", "Proposed"], ["approved", "Approved"], ["testing", "Testing"], ["validated", "Validated"], ["rejected", "Rejected"]].map(([k, l]) => (
            <button key={k} className={status === k ? "on" : ""} onClick={() => setStatus(k)}>{l}</button>
          ))}
        </div>
        <span className="small muted">{INDEX_NOTE}</span>
      </div>
      <ErrorBox error={error || act.error} onRetry={reload} />
      {loading && <Loading />}
      {data && data.length === 0 && (
        <div className="card"><Empty title="No opportunities yet">
          Opportunities are generated by an analysis with an AI model, and each one must cite real audience evidence.
          {audienceId && <div className="mt"><Link className="btn" to={`/audiences/${audienceId}`}>Go to analysis</Link></div>}
        </Empty></div>
      )}
      {data && data.length > 0 && (
        <div className="card" style={{ padding: 0 }}>
          <table className="t">
            <thead><tr><th style={{ paddingLeft: 20 }} title={INDEX_NOTE}>Index</th><th>Opportunity</th><th>Type</th><th className="num">Test price</th>
              <th className="num">Evidence</th><th>Status</th><th /></tr></thead>
            <tbody>
              {data.map((o) => (
                <tr key={o.id}>
                  <td style={{ paddingLeft: 20 }}><ScoreChip v={o.total_score} /></td>
                  <td style={{ maxWidth: 420 }}>
                    <div className="row" style={{ gap: 6 }}><Link className="strong" to={`/opportunities/${o.id}`}>{o.name}</Link><Demo on={o.is_demo} />
                      {!o.is_latest && <span className="badge" title="From an earlier analysis run">earlier run</span>}</div>
                    <div className="small muted">{o.buyer}</div>
                    {!audienceId && <div className="tiny faint">{o.audience_name}</div>}
                    {o.missing_evidence?.[0] && <div className="tiny" style={{ color: "var(--warn)" }}>{o.missing_evidence[0]}</div>}
                  </td>
                  <td className="small">{o.product_type}<div className="faint">{o.delivery_difficulty} difficulty</div></td>
                  <td className="num">{money(o.price, 0)}<div className="tiny faint">{o.price_model}</div></td>
                  <td className="num">{o.evidence_count}</td>
                  <td><Status s={o.status} /></td>
                  <td className="num" style={{ whiteSpace: "nowrap" }}>
                    {o.status === "proposed" && <button className="btn sm" onClick={() => setSt(o.id, "approved")} disabled={act.busy}>Approve</button>}{" "}
                    {o.status !== "rejected" && o.status !== "validated" && <button className="btn ghost sm" onClick={() => setSt(o.id, "rejected")} disabled={act.busy}>Reject</button>}
                    {o.status === "rejected" && <button className="btn ghost sm" onClick={() => setSt(o.id, "proposed")} disabled={act.busy}>Restore</button>}
                  </td>
                </tr>
              ))}
            </tbody>
          </table>
        </div>
      )}
    </div>
  );
}

export default function Opportunities() {
  return (
    <div className="page">
      <div className="page-head">
        <div>
          <h1>Product Opportunities</h1>
          <div className="sub">Products and services each audience might realistically buy, grounded in their own words. Prices and economics are hypotheses to test.</div>
        </div>
      </div>
      <OpportunityList />
    </div>
  );
}
